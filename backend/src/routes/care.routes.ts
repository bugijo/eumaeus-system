import { Router } from 'express';
import { requireRoles, ROLE } from '../middlewares/auth.middleware';
import { careController } from '../controllers/care.controller';
const router = Router();
const read = requireRoles(ROLE.DONO, ROLE.VETERINARIO, ROLE.RECEPCAO, ROLE.AUXILIAR);
const clinical = requireRoles(ROLE.DONO, ROLE.VETERINARIO);
router.get('/hospitalizations', read, careController.admissions);
router.post('/hospitalizations', clinical, careController.admit);
router.post('/hospitalizations/:id/tasks', clinical, careController.task);
router.patch('/hospitalization-tasks/:id/execute', requireRoles(ROLE.DONO, ROLE.VETERINARIO, ROLE.AUXILIAR), careController.executeTask);
router.post('/hospitalizations/:id/prescriptions', clinical, careController.prescription);
router.patch('/hospitalizations/:id/discharge', clinical, careController.discharge);
router.post('/hospitalizations/:id/handoffs', clinical, careController.handoff);
router.get('/surgeries', read, careController.surgeries);
router.post('/surgeries', clinical, careController.surgery);
router.post('/surgeries/:id/budgets', clinical, careController.budget);
router.post('/surgeries/:id/consents', clinical, careController.consent);
router.post('/surgeries/:id/checklist', clinical, careController.checklist);
router.patch('/surgery-checklist/:id/complete', requireRoles(ROLE.DONO, ROLE.VETERINARIO, ROLE.AUXILIAR), careController.completeChecklist);
router.post('/surgeries/:id/instructions', clinical, careController.instruction);
router.patch('/surgery-instructions/:id/approve', clinical, careController.approveInstruction);
export default router;
